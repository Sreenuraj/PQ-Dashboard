function getScenarioMetadata(idOrChecklistId) {
  if (!idOrChecklistId) return null;
  if (scenariosMetadata[idOrChecklistId]) return scenariosMetadata[idOrChecklistId];
  const found = Object.values(scenariosMetadata).find(
    (s) => s.checklistId === idOrChecklistId || s.id === idOrChecklistId
  );
  return found || null;
}

